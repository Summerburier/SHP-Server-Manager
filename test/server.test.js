test('配置验证与密码比较', () => {
  const base = { servers: [{ id: 'main', url: 'http://127.0.0.1:3000' }] };
  assert.equal(validateConfig(base).pollIntervalSeconds, 15);
  assert.throws(() => validateConfig({ servers: [...base.servers, ...base.servers] }));
  assert.throws(() => validateConfig({ servers: [{ id: 'x', url: 'file:///etc/passwd' }] }));
  assert.throws(() => validateConfig({ ...base, pollIntervalSeconds: 0 }));
  assert.throws(() => validateConfig({ servers: [{ ...base.servers[0], actions: { arbitrary: { command: 'echo', args: [] } } }] }));
  assert(secretEqual('secret', 'secret'));
  assert(!secretEqual('secret', 'other'));
});

test('采样、登录、历史、跨域防护、管理操作和退出', { timeout: 20000 }, async t => {
  const health = { ok: true, app: '0.2.6', uptimeSec: 100, sockets: 3, sessions: 4, rooms: 2, matches: 1, humans: 2, bots: 1, spectators: 0 };
  const game = http.createServer((req, res) => { assert.equal(req.url, '/healthz?traffic=1'); res.end(JSON.stringify(health)); });
  game.listen(0, '127.0.0.1'); await once(game, 'listening'); t.after(() => game.close());
  const gameUrl = `http://127.0.0.1:${game.address().port}`;
  assert.equal((await probe({ url: gameUrl })).health.humans, 2);
  const malformed = http.createServer((req, res) => res.end('{"ok":true}'));
  malformed.listen(0, '127.0.0.1'); await once(malformed, 'listening');
  assert.equal((await probe({ url: `http://127.0.0.1:${malformed.address().port}` })).online, false);
  await new Promise(resolve => malformed.close(resolve));
  const stalled = http.createServer(() => {}); stalled.listen(0, '127.0.0.1'); await once(stalled, 'listening');
  assert.equal((await probe({ url: `http://127.0.0.1:${stalled.address().port}` }, 50)).error, '连接超时');
  stalled.closeAllConnections(); await new Promise(resolve => stalled.close(resolve));
  const temp = await mkdtemp(join(tmpdir(), 'shp-admin-'));
  const actionFile = join(temp, 'action.txt'), configFile = join(temp, 'config.json');
  await writeFile(configFile, JSON.stringify({ servers: [{ id: 'main', name: '测试服', url: gameUrl, actions: { start: { command: process.execPath, args: ['-e', "require('fs').writeFileSync(process.argv[1], 'executed')", actionFile] } } }] }));
  await mkdir(join(temp, 'data'));
  const oldAt = Date.now() - 1000;
  await writeFile(join(temp, 'data', 'history.json'), JSON.stringify({main:[{at:oldAt,online:true,health}]}));
  await writeFile(join(temp, 'data', 'host-history.json'), JSON.stringify([{at:oldAt,cpuPercent:99}]));
  const child = spawn(process.execPath, ['src/server.js'], { cwd: new URL('..', import.meta.url), env: { ...process.env, HOST: '127.0.0.1', PORT: '0', ADMIN_TOKEN: 'test-secret-password-at-least-24-chars', CONFIG_FILE: configFile, DATA_DIR: join(temp, 'data') }, stdio: ['ignore', 'pipe', 'pipe'] });
  t.after(async () => { if (child.exitCode === null) { child.kill(); await once(child, 'exit'); } await rm(temp, { recursive: true, force: true }); });
  let output = '', errors = ''; child.stdout.on('data', d => output += d); child.stderr.on('data', d => errors += d);
  const deadline = Date.now() + 5000;
  while (!/http:\/\/127.0.0.1:(\d+)/.test(output) && Date.now() < deadline && child.exitCode === null) await new Promise(r => setTimeout(r, 20));
  const base = /http:\/\/127.0.0.1:(\d+)/.exec(output)?.[0]; assert(base, errors || output);
  assert.equal((await fetch(base + '/')).status, 200);
  assert.equal((await fetch(base + '/api/status')).status, 401);
  assert.equal((await fetch(base + '/api/host/history')).status, 401);
  assert.equal((await fetch(base + '/api/plugins')).status, 401);
  const html = await (await fetch(base + '/')).text();
  const script = /src="([^"]+\.js)"/.exec(html)?.[1];
  assert(script, '应返回构建后的 Vue 入口');
  assert.equal((await fetch(base + script)).status, 200);
  const login = (token, username = 'admin') => fetch(base + '/api/login', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ username, password: token }) });
  assert.equal((await login('wrong')).status, 401);
  const result = await login('test-secret-password-at-least-24-chars'); assert.equal(result.status, 200);
  assert(result.headers.get('set-cookie').includes('HttpOnly'));
  const auth = { Cookie: result.headers.get('set-cookie').split(';')[0] };
  const settingsResponse = await fetch(base + '/api/settings', {headers:auth});
  const settings = await settingsResponse.json();assert(settings.config.servers.length === 1);
  assert(!JSON.stringify(settings).includes('test-secret-password'));
  const newPassword = 'new-pass8';
  const payload = {config:{...settings.config,pluginsDirectory:settings.pluginsDirectory},currentPassword:'wrong',newPassword,adminUsername:'operator'};
  assert.equal((await fetch(base + '/api/settings',{method:'POST',headers:auth,body:JSON.stringify(payload)})).status,400);
  payload.currentPassword='test-secret-password-at-least-24-chars';
  assert.equal((await fetch(base + '/api/settings',{method:'POST',headers:auth,body:JSON.stringify(payload)})).status,200);
  assert.equal((await login('test-secret-password-at-least-24-chars')).status,401);
  assert.equal((await login(newPassword,'operator')).status,200);
  assert.equal((await login(newPassword,'admin')).status,401);
  assert.equal((await (await fetch(base+'/api/settings',{headers:auth})).json()).adminUsername,'operator');
  const authFile=await readFile(join(temp,'data','admin-auth.json'),'utf8');assert(!authFile.includes(newPassword));
  const installed = await (await fetch(base + '/api/plugins', { headers: auth })).json();
  assert(Array.isArray(installed.plugins)); assert(Array.isArray(installed.instances));
  assert.equal((await fetch(base + '/api/plugins/rescan', { method: 'POST', headers: { ...auth, Origin: 'http://attacker.invalid' } })).status, 403);
  assert.equal((await fetch(base + '/api/plugins/instances/missing/enable', { method: 'POST', headers: auth })).status, 400);
  assert.equal((await fetch(base + '/api/plugins/missing/instances', { method: 'POST', headers: auth })).status, 400);
  let status;
  for (let i = 0; i < 50; i++) { status = await (await fetch(base + '/api/status', { headers: auth })).json(); if (status.servers[0].online) break; await new Promise(r => setTimeout(r, 20)); }
  assert.equal(status.servers[0].health.humans, 2);
  for (let i = 0; i < 500 && !status.host; i++) { await new Promise(r => setTimeout(r, 20)); status = await (await fetch(base + '/api/status', { headers: auth })).json(); }
  assert(status.host.memoryTotal > 0);
  assert(status.startedAt > oldAt);
  for (const path of ['/api/history?id=main', '/api/host/history']) {
    const points = await (await fetch(base + path, { headers: auth })).json();
    assert(points.length > 0);
    assert(points.every(point => point.at >= status.startedAt), '上次运行的采样不应载入');
  }
  assert(Array.isArray(status.host.cpuCores));
  assert(Array.isArray(status.host.disks));
  assert.equal(status.hostPollIntervalSeconds, 5);
  const hostHistory = await (await fetch(base + '/api/host/history', { headers: auth })).json();
  assert.equal(hostHistory.length, 1);
  assert.equal(typeof hostHistory[0].memoryPercent, 'number');
  const futureHistory = await (await fetch(base + '/api/host/history?since=' + (Date.now() + 60000), { headers: auth })).json();
  assert.deepEqual(futureHistory, []);
  assert.equal((await fetch(base + '/api/host/history?since=invalid', { headers: auth })).status, 400);
  assert.deepEqual(status.servers[0].actions, ['start']);
  const history = await (await fetch(base + '/api/history?id=main', { headers: auth })).json(); assert.equal(history[0].health.matches, 1);
  assert.equal((await fetch(base + '/api/servers/main/actions/start', { method: 'POST', headers: { ...auth, Origin: 'http://attacker.invalid' } })).status, 403);
  assert.equal((await fetch(base + '/api/servers/main/actions/stop', { method: 'POST', headers: auth })).status, 403);
  assert.equal((await fetch(base + '/api/servers/main/actions/start', { method: 'POST', headers: auth })).status, 200);
  assert.equal(await readFile(actionFile, 'utf8'), 'executed');
  assert.match(await readFile(join(temp, 'data', 'audit.jsonl'), 'utf8'), /success/);
  assert.equal(JSON.parse(await readFile(join(temp, 'data', 'history.json'), 'utf8')).main[0].health.humans, 2);
  assert.equal(JSON.parse(await readFile(join(temp, 'data', 'host-history.json'), 'utf8'))[0].memoryPercent, hostHistory[0].memoryPercent);
  assert.equal((await fetch(base + '/api/logout', { method: 'POST', headers: auth })).status, 200);
  assert.equal((await fetch(base + '/api/status', { headers: auth })).status, 401);
});
