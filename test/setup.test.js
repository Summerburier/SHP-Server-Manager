import {test} from 'node:test';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {once} from 'node:events';
import {mkdtemp,writeFile,readFile,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';import {join} from 'node:path';
test('首次初始化、验证码保护、保存服务即时接入与本地日志', {timeout:20000}, async t=>{
 const temp=await mkdtemp(join(tmpdir(),'shp-setup-'));
 const config=join(temp,'config.json');await writeFile(config,JSON.stringify({servers:[],pluginsDirectory:join(temp,'plugins')}));
 await writeFile(join(temp,'app.js'),"console.log('service-log-ready');setInterval(()=>{},1000);");
 const child=spawn(process.execPath,['src/server.js'],{cwd:new URL('..',import.meta.url),env:{...process.env,ADMIN_PASSWORD:'',ADMIN_TOKEN:'',CONFIG_FILE:config,DATA_DIR:join(temp,'data'),PLUGINS_DIR:join(temp,'plugins'),PORT:'0',HOST:'127.0.0.1'},stdio:['ignore','pipe','pipe']});
 t.after(async()=>{if(child.exitCode===null){const ended=once(child,'exit');child.kill();await ended;}await rm(temp,{recursive:true,force:true});});
 let output='',errors='';child.stdout.on('data',d=>output+=d);child.stderr.on('data',d=>errors+=d);
 const deadline=Date.now()+7000;while(!/http:\/\/127.0.0.1:(\d+)/.test(output)&&Date.now()<deadline)await new Promise(r=>setTimeout(r,20));
 const base=/http:\/\/127.0.0.1:(\d+)/.exec(output)?.[0];assert(base,errors);
 const pin=/首次配置验证码：([a-f0-9]+)/.exec(output)?.[1];assert(pin);
 assert.equal((await (await fetch(base+'/api/setup')).json()).required,true);
 const post=(path,data,headers={})=>fetch(base+path,{method:'POST',headers:{'Content-Type':'application/json',...headers},body:JSON.stringify(data)});
 assert.equal((await post('/api/setup',{pin:'wrong',username:'admin',password:'password8'})).status,400);
 assert.equal((await post('/api/setup',{pin,username:'admin',password:'password8'})).status,200);
 assert.equal((await post('/api/setup',{pin,username:'admin',password:'password8'})).status,409);
 assert.equal((await (await fetch(base+'/api/setup')).json()).required,false);
 const login=await post('/api/login',{username:'admin',password:'password8'});assert.equal(login.status,200);
 const auth={Cookie:login.headers.get('set-cookie').split(';')[0]};
 assert.equal((await post('/api/services',{servers:[{id:'remote',url:'http://192.168.1.1:3000'}]},auth)).status,400);
 const service={id:'local',name:'Local',source:temp,projectOptions:{entry:'app.js'}};
 let saved;for(let n=0;n<20;n++){saved=await post('/api/services',{servers:[service]},auth);if(saved.status!==409)break;await new Promise(r=>setTimeout(r,50));}assert.equal(saved.status,200);
 assert.equal((await (await fetch(base+'/api/status',{headers:auth})).json()).servers[0].id,'local');
 assert.equal((await post('/api/servers/local/actions/start',{},auth)).status,200);
 let logs;for(let n=0;n<40;n++){logs=await (await fetch(base+'/api/servers/local/logs',{headers:auth})).json();if(logs.text.includes('service-log-ready'))break;await new Promise(r=>setTimeout(r,30));}assert(logs.text.includes('service-log-ready'));
 assert.equal((await post('/api/servers/local/actions/stop',{},auth)).status,200);
 assert.equal((await post('/api/services',{servers:[]},auth)).status,200);
 const empty=await (await fetch(base+'/api/status',{headers:auth})).json();assert.deepEqual(empty.servers,[]);
 assert.deepEqual(JSON.parse(await readFile(config,'utf8')).servers,[]);
 const stored=await readFile(join(temp,'data','admin-auth.json'),'utf8');assert(!stored.includes('password8'));
});
